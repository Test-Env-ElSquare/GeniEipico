using Application.Services;
using Domain.Entities.IoT;
var tags = new Dictionary<string,TelemetryTag>(StringComparer.OrdinalIgnoreCase);
var at = new DateTime(2026,9,30,16,0,0);
var passed=0;
Check(!EnergySignalMapper.IsComplete(tags), "Empty not complete");
foreach(var name in EnergySignalMapper.RequiredTags.Take(26))
    tags[name] = new TelemetryTag { TagName=name, ValueNum=12.5m, RecordedAt=at };
Check(!EnergySignalMapper.IsComplete(tags), "Partial page not complete");
tags["thdi3"] = new TelemetryTag { TagName="thdi3", ValueNum=12.5m, RecordedAt=at };
Check(EnergySignalMapper.IsComplete(tags), "Case-insensitive complete group");
var row=EnergySignalMapper.Create(tags,at);
Check(row.VoltageL1==12.5m,"V1 maps to VoltageL1");
Check(row.VoltageL2==12.5m,"V2 maps to VoltageL2");
Check(row.VoltageL3==12.5m,"V3 maps to VoltageL3");
Check(row.CurrentL1==12.5m,"I1 maps to CurrentL1");
Check(row.CurrentL2==12.5m,"I2 maps to CurrentL2");
Check(row.CurrentL3==12.5m,"I3 maps to CurrentL3");
Check(row.PowerFactorL1==12.5m,"Pf1 maps to PowerFactorL1");
Check(row.PowerFactorL2==12.5m,"Pf2 maps to PowerFactorL2");
Check(row.PowerFactorL3==12.5m,"Pf3 maps to PowerFactorL3");
Check(row.ActivePowerL1==12.5m,"Pact1 maps to ActivePowerL1");
Check(row.ActivePowerL2==12.5m,"Pact2 maps to ActivePowerL2");
Check(row.ActivePowerL3==12.5m,"Pact3 maps to ActivePowerL3");
Check(row.ReactivePowerL1==12.5m,"Preact1 maps to ReactivePowerL1");
Check(row.ReactivePowerL2==12.5m,"Preact2 maps to ReactivePowerL2");
Check(row.ReactivePowerL3==12.5m,"Preact3 maps to ReactivePowerL3");
Check(row.ApparentPowerL1==12.5m,"Papp1 maps to ApparentPowerL1");
Check(row.ApparentPowerL2==12.5m,"Papp2 maps to ApparentPowerL2");
Check(row.ApparentPowerL3==12.5m,"Papp3 maps to ApparentPowerL3");
Check(row.EnergyL1==12.5m,"Energy1 maps to EnergyL1");
Check(row.EnergyL2==12.5m,"Energy2 maps to EnergyL2");
Check(row.EnergyL3==12.5m,"Energy3 maps to EnergyL3");
Check(row.VoltageThdL1==12.5m,"THDv1 maps to VoltageThdL1");
Check(row.VoltageThdL2==12.5m,"THDv2 maps to VoltageThdL2");
Check(row.VoltageThdL3==12.5m,"THDv3 maps to VoltageThdL3");
Check(row.CurrentThdL1==12.5m,"THDi1 maps to CurrentThdL1");
Check(row.CurrentThdL2==12.5m,"THDi2 maps to CurrentThdL2");
Check(row.CurrentThdL3==12.5m,"THDi3 maps to CurrentThdL3");
Check(row.Timestamp==at,"No second timezone conversion");
Check(row.Quality is null,"Quality null");
tags["V1"].ValueNum=null;
Check(EnergySignalMapper.Create(tags,at).VoltageL1 is null,"Nonnumeric tag remains null");
tags["V1"].ValueNum=0;
Check(EnergySignalMapper.Create(tags,at).VoltageL1==0,"Zero preserved");
Check(row.FactoryId==0 && row.TransformerId==0 && row.LineId is null,"No hardcoded scope");
Console.WriteLine($"PASS: {passed} projection mapping checks; no database writes.");
void Check(bool value,string message) { if(!value) throw new Exception(message); passed++; }
